<?php

namespace App\Console\Commands;

use App\Jobs\ProcessSimulation;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;

class DemoSimulation extends Command
{
    protected $signature = 'marketplace:simulate-demo {--sync : Process immediately instead of queuing}';

    protected $description = 'Generate a private candidate animation from the demo brake assembly';

    public function handle(): int
    {
        if (app()->environment('production')) {
            $this->error('Demo generation is disabled in production.');

            return self::FAILURE;
        }
        $model = DB::table('simulation_models')->where('model_type', 'procedural')->first();
        $source = DB::table('repair_procedures')->where('is_concept', true)->first();
        if (! $model || ! $source) {
            $this->error('Seed the demo catalog first.');

            return self::FAILURE;
        }
        $job = DB::transaction(function () use ($model, $source) {
            $id = DB::table('repair_procedures')->insertGetId(['title' => 'Generated brake assembly candidate', 'description' => 'Concept animation generated by Blender, awaiting review.', 'status' => 'draft', 'source_reference' => 'Project-authored procedural geometry', 'is_concept' => true, 'created_at' => now(), 'updated_at' => now()]);
            foreach (['repair_procedure_vehicles', 'repair_procedure_parts', 'repair_steps'] as $table) {
                foreach (DB::table($table)->where('procedure_id', $source->id)->get() as $row) {
                    $data = (array) $row;
                    unset($data['id']);
                    $data['procedure_id'] = $id;
                    $data['created_at'] = now();
                    $data['updated_at'] = now();
                    DB::table($table)->insert($data);
                }
            }

            return DB::table('simulation_jobs')->insertGetId(['procedure_id' => $id, 'source_model_id' => $model->id, 'created_at' => now(), 'updated_at' => now()]);
        });
        if ($this->option('sync')) {
            try {
                (new ProcessSimulation($job))->handle();
            } catch (\Throwable $e) {
                (new ProcessSimulation($job))->failed($e);
                $this->error($e->getMessage());

                return self::FAILURE;
            }
        } else {
            ProcessSimulation::dispatch($job);
        }
        $this->info("Simulation job #{$job} created. Review it in /admin.");

        return self::SUCCESS;
    }
}
